"""
📝 Steps

Step 1: Install Git. Download Git for Windows from git-scm.com and install it with the default options.

Step 2: Check it works. Open a new terminal in VS Code (an old one won’t see Git) and run:

git --version

Step 3: Tell Git who you are (once). Use your name and a personal email, not your company email:

git config --global user.name "Your Name"
git config --global user.email "you@example.com"

Step 4: Choose the project folder. Use the folder you made earlier, such as Documents\python-journey. It should not be inside OneDrive or Downloads. Open that folder in VS Code (File → Open Folder).

Step 5: Make your first commit. In the terminal inside that folder:

git init
git status
git add Guessing_Game.py
git commit -m "Add guessing game with high score"
git log
"""